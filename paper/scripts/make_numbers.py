#!/usr/bin/env python3
"""Every measured or derived number of the manuscript, as LaTeX macros and tables in generated/.

Author: Nasir Ali, C-DAC Noida.

Sources (nothing is typed by hand except NVIDIA's published values, marked below with their table):
  runs/ler/*.json                         logical error rates through NVIDIA's evaluation (harness/eval_ler.py)
  runs/hw/cards_*.json                    card campaign: bit exact checks, throughput, latency (bench/run_cards.py)
  runs/cpu/cpu_*.json                     PyTorch on the host CPU (bench/cpu_torch_throughput.py)
  four_card_decoder/build/hw/             routed utilisation and timing, xclbin info (or stored copies in reports/)
  runs/logs/csynth_v3.log                 HLS estimate of the kernel
  runs/host_platform.json                 host CPU, memory, XRT and package versions (recorded on the host)
A missing source leaves \\PENDING{...} markers (refused by the final build).
usage: make_numbers.py
"""
import glob
import json
import os
import re
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.abspath(os.path.join(HERE, ".."))
ND = os.path.abspath(os.path.join(PAPER, ".."))
RUNS = os.environ.get("NPD_RUNS", os.path.join(ND, "results"))
BUILD = os.environ.get("NPD_BUILD", os.path.join(ND, "build", "hw"))
GEN = os.path.join(PAPER, "generated")
M = {}

# NVIDIA's published improvement factors, X basis, uncorrelated PyMatching (Chamberland et al., arXiv:2604.12841,
# Table 4 for p = 0.006 and Table 5 for p = 0.003); model 1 = Fast, model 4 = Accurate
NVIDIA = {("fast", 0.006, 9): 1.24, ("fast", 0.006, 13): 1.27, ("fast", 0.003, 9): 1.10, ("fast", 0.003, 13): 0.91,
          ("accurate", 0.006, 13): 1.76, ("accurate", 0.003, 13): 1.32}


def pend(what):
    return r"\PENDING{" + what + "}"


def fmt_int(x):
    return f"{int(round(x)):,}".replace(",", "{,}")


def fmt(x, nd=2):
    return f"{x:.{nd}f}"


def write(name, lines):
    os.makedirs(GEN, exist_ok=True)
    open(os.path.join(GEN, name), "w").write("% generated by scripts/make_numbers.py\n" + "\n".join(lines) + "\n")


def net_of(rec):
    return "accurate" if "accurate" in rec["checkpoint"] else "fast"


# ---------------------------------------------------------------- logical error rates
def ler():
    rows = []
    for f in sorted(glob.glob(os.path.join(RUNS, "ler", "*.json"))):
        d = json.load(open(f))
        if d.get("variant") not in ("fp32", "int8") or "result" not in d:
            continue
        p = d.get("p", 0.003)
        r = {b: d["result"][b] for b in ("X", "Z")}
        after = sum(int(r[b]["logical errors"]) for b in r)
        pm = sum(int(r[b]["pymatch flips"]) for b in r)
        shots = int(r["X"]["num shots"])
        rows.append(dict(net=net_of(d), variant=d["variant"], d=d["d"], p=p, shots=shots, after=after, pm=pm,
                         ratio=pm / after, ratio_x=int(r["X"]["pymatch flips"]) / int(r["X"]["logical errors"]),
                         x_pm=int(r["X"]["pymatch flips"]), x_after=int(r["X"]["logical errors"]),
                         file=os.path.basename(f)))
    # one row per configuration: the run with the most shots
    best = {}
    for r in rows:
        k = (r["net"], r["variant"], r["d"], r["p"])
        if k not in best or r["shots"] > best[k]["shots"]:
            best[k] = r
    order = sorted(best.values(), key=lambda r: (r["net"] != "fast", r["p"], r["d"], r["variant"]))
    lines = [r"\begin{tabular}{@{}llrrrrrrr@{}}", r"\toprule",
             r"Network & Arithmetic & $d$ & $p$ & Shots per basis & PyMatching & With pre-decoder & Ratio, X & "
             r"NVIDIA, X \\", r"\midrule"]
    for r in order:
        nv = NVIDIA.get((r["net"], r["p"], r["d"]))
        lines.append(f"{'Fast' if r['net'] == 'fast' else 'Accurate'} & {'FP32' if r['variant'] == 'fp32' else 'INT8'} & "
                     f"{r['d']} & {r['p']:.3f} & {fmt_int(r['shots'])} & {fmt_int(r['pm'])} & {fmt_int(r['after'])} & "
                     f"{fmt(r['ratio_x'])} & {fmt(nv) if nv else 'n.a.'} " + r"\\")
    lines += [r"\botrule", r"\end{tabular}"]
    write("tab_ler.tex", lines)
    def key(net, var, d, p):
        return best.get((net, var, d, p))
    for name, (net, var, d, p) in {"FastFpNineLow": ("fast", "fp32", 9, 0.003), "FastFpThirteenLow": ("fast", "fp32", 13, 0.003),
                                   "FastFpNineHigh": ("fast", "fp32", 9, 0.006), "FastIntNineHigh": ("fast", "int8", 9, 0.006),
                                   "FastIntNineLow": ("fast", "int8", 9, 0.003),
                                   "AccFpThirteenHigh": ("accurate", "fp32", 13, 0.006),
                                   "AccFpThirteenLow": ("accurate", "fp32", 13, 0.003),
                                   "AccIntThirteenHigh": ("accurate", "int8", 13, 0.006)}.items():
        r = key(net, var, d, p)
        M[f"Ratio{name}"] = fmt(r["ratio"]) if r else pend(f"LER {name}")
        M[f"RatioX{name}"] = fmt(r["ratio_x"]) if r else pend(f"LER {name}")
        M[f"Shots{name}"] = fmt_int(r["shots"]) if r else pend(f"shots {name}")
    # integer Accurate network: errors after the pre-decoder, and the count expected on the same shots from the
    # floating point factor
    ri, rf = key("accurate", "int8", 13, 0.006), key("accurate", "fp32", 13, 0.006)
    M["IntAccAfter"] = fmt_int(ri["after"]) if ri else pend("int8 errors")
    M["IntAccExpected"] = fmt_int(ri["pm"] / rf["ratio"]) if ri and rf else pend("expected errors")
    # the text states that every floating point X factor is within 0.07 of NVIDIA's and below it
    fp = [(r["ratio_x"], NVIDIA[(r["net"], r["p"], r["d"])]) for r in best.values()
          if r["variant"] == "fp32" and (r["net"], r["p"], r["d"]) in NVIDIA]
    assert fp and all(0 <= nv - ours <= 0.07 + 1e-9 for ours, nv in fp), f"text on agreement no longer holds: {fp}"
    return best


# ---------------------------------------------------------------- CPU baseline
def cpu():
    out = {}
    M["CpuThreads"] = M["CpuThreadList"] = M["CpuReps"] = pend("CPU threads")
    for net, f in (("fast", "cpu_fast_d9.json"), ("accurate", "cpu_accurate_d13.json")):
        p = os.path.join(RUNS, "cpu", f)
        if not os.path.exists(p):
            M[f"Cpu{net.title()}Best"] = M[f"Cpu{net.title()}One"] = M[f"Cpu{net.title()}BestBatch"] = pend("CPU")
            continue
        d = json.load(open(p))
        rows = [r for r in d["rows"] if r["dtype"] == "float32"]
        best = max(rows, key=lambda r: r["windows_per_s"])                            # over threads, batch, repetition
        one = max((r for r in rows if r["batch"] == 1), key=lambda r: r["windows_per_s"])
        M[f"Cpu{net.title()}Best"] = fmt_int(best["windows_per_s"])
        M[f"Cpu{net.title()}BestBatch"] = str(best["batch"])
        M[f"Cpu{net.title()}BestThreads"] = str(best.get("threads", d["threads"]))
        M[f"Cpu{net.title()}One"] = fmt_int(one["windows_per_s"])
        M[f"Cpu{net.title()}OneMs"] = fmt(1e3 / one["windows_per_s"])
        M[f"Cpu{net.title()}OneThreads"] = str(one.get("threads", d["threads"]))
        th = d["threads"] if isinstance(d["threads"], list) else [d["threads"]]
        M["CpuThreads"] = str(max(th))
        M["CpuThreadList"] = ", ".join(map(str, th[:-1])) + " and " + str(th[-1]) if len(th) > 1 else str(th[0])
        M["CpuReps"] = str(1 + max(r.get("rep", 0) for r in rows))
        M["TorchVersion"] = d["torch"].split("+")[0]
        g = {}
        for r in rows:
            g.setdefault((r.get("threads"), r["batch"]), []).append(r["windows_per_s"])
        var = sorted(100 * (max(v) / min(v) - 1) for v in g.values() if len(v) > 1)
        if var:
            M[f"CpuVarMed{net.title()}"] = fmt(var[len(var) // 2], 0)
            M[f"CpuVarMax{net.title()}"] = fmt(var[-1], 0)
        out[net] = dict(best=best["windows_per_s"], one=one["windows_per_s"], rows=rows)
    return out


# ---------------------------------------------------------------- cards
def cards(cpu_rates):
    files = sorted(glob.glob(os.path.join(RUNS, "hw", "cards_*.json")))
    if not files:
        for k in ("FourFast", "FourAcc", "OneFast", "OneAcc", "SpeedFast", "SpeedAcc", "LatFast", "LatAcc",
                  "CheckCount", "ScaleFast", "ScaleAcc"):
            M[k] = pend("cards")
        return None
    d = json.load(open(files[-1]))
    M["CheckCount"] = str(sum(1 for c in d["check"] if c["bit_exact"]))
    M["CheckTotal"] = str(len(d["check"]))
    M["CheckInstances"] = str(sum(c["instances"] for c in d["check"]))
    assert all(c["bit_exact"] for c in d["check"]), "a bit exact check failed"
    lines = [r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
             r"Network & Cards & Windows/s (median) & Range & Per card & Scaling \\", r"\midrule"]
    res = {}
    for net, short in (("fast", "Fast"), ("accurate", "Acc")):
        pts = {}
        for n in (1, 2, 4):
            v = [b["aggregate_windows_per_sec"] for b in d["bench"] if b["net"] == net and b["cards"] == n]
            if v:
                pts[n] = (statistics.median(v), min(v), max(v))
        if not pts:
            continue
        for n, (med, lo, hi) in sorted(pts.items()):
            lines.append(f"{'Fast, $d=9$' if net == 'fast' else 'Accurate, $d=13$'} & {n} & {fmt_int(med)} & "
                         f"{fmt_int(lo)} to {fmt_int(hi)} & {fmt_int(med / n)} & {fmt(med / (n * pts[1][0]))} " + r"\\")
        M[f"One{short}"] = fmt_int(pts[1][0])
        M[f"Four{short}"] = fmt_int(pts[4][0]) if 4 in pts else pend("4 cards")
        M[f"Scale{short}"] = fmt(pts[4][0] / (4 * pts[1][0])) if 4 in pts else pend("scaling")
        if net in cpu_rates and 4 in pts:
            M[f"Speed{short}"] = fmt(pts[4][0] / cpu_rates[net]["best"], 1)
            M[f"HostCards{short}"] = fmt(cpu_rates[net]["best"] / pts[1][0], 1)
        else:
            M[f"Speed{short}"] = pend("speedup")
        lat = [x for x in d["latency"] if x["net"] == net]
        M[f"Lat{short}"] = fmt(lat[0]["per_window_s"] * 1e3) if lat else pend("latency")
        inst = [b for b in d["bench"] if b["net"] == net and b["cards"] == 1]
        M[f"PerInst{short}"] = fmt_int(pts[1][0] / sum(inst[0]["instances_per_card"])) if inst else pend("instance")
        res[net] = pts
        lines.append(r"\midrule" if net == "fast" else "")
    lines = [l for l in lines if l != ""]
    if lines[-1] == r"\midrule":
        lines.pop()
    lines += [r"\botrule", r"\end{tabular}"]
    write("tab_throughput.tex", lines)
    # temperatures
    t = [v["fpga_c"] for e in d["temps"] for v in e["temps"].values() if v.get("fpga_c") is not None]
    M["TempMax"] = str(max(t)) if t else pend("temperature")
    return res


# ---------------------------------------------------------------- cycle model
def cycles(L, d):
    """Cycles per window of the kernel from its loop structure and the scheduled depths (HLS report)."""
    s = d * d * d
    tot = 2 + s + 3 + 2 + s + 3
    for l in range(L):
        cin = 1 if l == 0 else 8
        cob = 1 if l == L - 1 else 2
        per = 256 + 15 if l < L - 1 else 0
        for _ in range(cob):
            per += 64 * 2 + 3 + (s + 2) + 27 * cin * ((64 + 6) + (s + 14)) + (s + 8)
        tot += per
    return tot


def macs(L, d):
    per_site = 4 * 128 * 27 + (L - 2) * 128 * 128 * 27 + 128 * 4 * 27
    return per_site * d ** 3


# ---------------------------------------------------------------- build
def build(card_res):
    util = sorted(glob.glob(os.path.join(BUILD, "_x", "**", "*kernel_util_routed.rpt"), recursive=True)) or \
        sorted(glob.glob(os.path.join(BUILD, "reports", "*kernel_util_routed.rpt")))
    try:
        u = open(util[0]).read()
        hdr = re.search(r"\|\s*Name\s*\|(.*)\|\s*\n", u).group(1)
        cols = [c.strip() for c in hdr.split("|")]
        def row(label):
            m = re.search(r"\|\s*" + re.escape(label) + r"\s*\|(.*)\|", u)
            return dict(zip(cols, [c.strip() for c in m.group(1).split("|")])) if m else None
        one = row("predecoder_1")
        lines = [r"\begin{tabular}{@{}lrr@{}}", r"\toprule", r"Resource & One instance & Percent of one SLR \\",
                 r"\midrule"]
        slr = {"LUT": 434560, "REG": 869120, "DSP": 3008, "BRAM": 672, "URAM": 320}
        for res, label in (("LUT", "LUT"), ("REG", "Flip flops"), ("DSP", "DSP blocks"), ("BRAM", "BRAM (36 kbit)"),
                           ("URAM", "URAM")):
            k = [c for c in cols if c.startswith(res)]
            if not k:
                continue
            v = float(one[k[0]].split("[")[0].replace(",", ""))
            lines.append(f"{label} & {fmt_int(v)} & {fmt(100 * v / slr[res], 1)} " + r"\\")
            M[f"Util{res.title()}"] = fmt_int(v)
        lines += [r"\botrule", r"\end{tabular}"]
        write("tab_resources.tex", lines)
    except Exception as e:  # noqa: BLE001
        write("tab_resources.tex", [pend(f"utilisation ({e})")])
    try:
        t = (sorted(glob.glob(os.path.join(BUILD, "_x", "**", "*timing_summary_postroute_physopted.rpt"), recursive=True))
             or [os.path.join(BUILD, "reports", "timing_summary_extract.txt")])[0]
        s = open(t).read()
        r = re.search(r"WNS\(ns\)\s+TNS\(ns\)\s+TNS Failing Endpoints.*?\n\s*-[-\s]+\n\s*([-\d.]+)\s+([-\d.]+)\s+(\d+)", s, re.S)
        M["Wns"] = r.group(1)
    except Exception:  # noqa: BLE001
        M["Wns"] = pend("timing")
    try:
        info = open(os.path.join(BUILD, "predecoder.xclbin.info")).read()
        mhz = re.findall(r"Name:\s*(\S+)\s*\n\s*Index:.*?\n\s*Type:\s*(\S+).*?\n\s*Frequency:\s*([\d.]+)", info)
        k = [f for n, typ, f in mhz if typ.upper() == "DATA"]
        M["KernelMhz"] = str(int(float(k[0]))) if k else pend("kernel clock")
    except Exception:  # noqa: BLE001
        M["KernelMhz"] = pend("kernel clock")
    # cycle model against measurement
    mhz = float(M["KernelMhz"]) if not M["KernelMhz"].startswith("\\") else 300.0
    for net, short, L, d in (("fast", "Fast", 4, 9), ("accurate", "Acc", 6, 13)):
        c = cycles(L, d)
        M[f"Cycles{short}"] = fmt_int(c)
        M[f"Macs{short}"] = fmt_int(macs(L, d))
        M[f"Model{short}"] = fmt_int(mhz * 1e6 / c)
        M[f"MacPerCycle{short}"] = fmt_int(macs(L, d) / c)
        M[f"ComputeMs{short}"] = fmt(1e3 * c / (mhz * 1e6))
        if not M.get(f"Lat{short}", "\\").startswith("\\"):
            M[f"LatOverhead{short}"] = fmt(float(M[f"Lat{short}"]) - 1e3 * c / (mhz * 1e6))
        else:
            M[f"LatOverhead{short}"] = pend("latency overhead")
        # products per second: achieved on four cards, and needed for one window of T = d rounds per d microseconds
        M[f"RealTimeTmac{short}"] = fmt(macs(L, d) / (d * 1e-6) / 1e12, 0)
        M[f"RealTimeWps{short}"] = fmt_int(1e6 / d)
        if card_res and net in card_res and 4 in card_res[net]:
            M[f"Tmac{short}"] = fmt(card_res[net][4][0] * macs(L, d) / 1e12)
        else:
            M[f"Tmac{short}"] = pend("products per second")
        if card_res and net in card_res:
            per_inst = card_res[net][1][0] / 2
            M[f"ModelEff{short}"] = fmt(100 * per_inst / (mhz * 1e6 / c), 0)
        else:
            M[f"ModelEff{short}"] = pend("model efficiency")


def hls():
    p = [q for q in (os.path.join(RUNS, "logs", "csynth_v3.log"), os.path.join(RUNS, "hls", "csynth_v3.log"))
         if os.path.exists(q)]
    s = open(p[0]).read() if p else ""
    m = re.search(r"Estimated Fmax:\s*([\d.]+)", s)
    M["HlsFmax"] = m.group(1).split(".")[0] if m else pend("HLS Fmax")


def platform():
    p = os.path.join(RUNS, "host_platform.json")
    keys = ("HostCpu", "HostThreads", "HostSockets", "HostMemGiB", "XrtVersion", "StimVersion", "PymatchingVersion",
            "TorchVersion", "NvidiaCommit")
    d = json.load(open(p)) if os.path.exists(p) else {}
    for k in keys:
        M[k] = d.get(k, pend(k))


def main():
    M["DevicePeakTmac"] = fmt(9024 * 2 * 300e6 / 1e12, 1)  # all DSP blocks, two 8 bit products each, 300 MHz
    platform()
    hls()
    ler()
    c = cpu()
    res = cards(c)
    build(res)
    lines = [f"\\newcommand{{\\Num{k}}}{{{v}}}" for k, v in sorted(M.items())]
    write("macros.tex", lines)
    n_pend = sum("PENDING" in v for v in M.values())
    print(f"generated/macros.tex: {len(M)} macros, {n_pend} pending")


if __name__ == "__main__":
    main()
